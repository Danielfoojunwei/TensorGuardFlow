    AUTO_ROLLBACK_TRIGGERED = "auto_rollback_triggered"
    AUTO_FREEZE_TRIGGERED = "auto_freeze_triggered"
    AUTO_QUARANTINE_TRIGGERED = "auto_quarantine_triggered"
    INVESTIGATION_OPENED = "investigation_opened"
    ACTION_BLOCKED_POLICY = "action_blocked_policy"
    ACTION_BLOCKED_COOLDOWN = "action_blocked_cooldown"
    ACTION_BLOCKED_SIGNATURE = "action_blocked_signature"
    SIGNAL_ACKNOWLEDGED = "signal_acknowledged"


