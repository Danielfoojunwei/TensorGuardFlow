import time
from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Any, Dict, List, Optional, Callable

from tensorguard.integrations.connectors.robotics.schemas import (
    InboundOpsSignal,
    OutboundOpsEvent,
    EventPayload,
    ActionContext,
    EvidenceRefs,
    Severity,
    EventCategory,
    OutboundEventType,
    InboundSignalType,
    ActionType,
    SignalSource,
    DEFAULT_SIGNAL_ACTION_MAP,
    get_default_action_for_signal,
)


# =============================================================================
# ROUTE POLICY CONFIGURATION
# =============================================================================


@dataclass
class OpsSignalPolicy:
    """Policy configuration for handling ops signals on a route."""
    # Automation controls
    allow_auto_rollback: bool = True
    allow_auto_freeze: bool = True
    allow_auto_quarantine: bool = True
    require_verified_signature_for_automation: bool = True

    # Thresholds
    cooldown_window_sec: int = 300  # 5 minutes between auto-actions
    max_auto_actions_per_hour: int = 5

    # Signal type overrides
    signal_type_actions: Dict[str, ActionType] = field(default_factory=dict)

    # Severity overrides
    critical_always_freeze: bool = True
    warn_requires_investigation: bool = True

    def to_dict(self) -> Dict[str, Any]:
        return {
            "allow_auto_rollback": self.allow_auto_rollback,
            "allow_auto_freeze": self.allow_auto_freeze,
            "allow_auto_quarantine": self.allow_auto_quarantine,
            "require_verified_signature_for_automation": self.require_verified_signature_for_automation,
            "cooldown_window_sec": self.cooldown_window_sec,
            "max_auto_actions_per_hour": self.max_auto_actions_per_hour,
            "signal_type_actions": {
                k: v.value for k, v in self.signal_type_actions.items()
            },
            "critical_always_freeze": self.critical_always_freeze,
            "warn_requires_investigation": self.warn_requires_investigation,
        }


