@dataclass
class ActionResult:
    """Result of executing an action."""
    success: bool
    action: ActionType
    message: str
    details: Dict[str, Any] = field(default_factory=dict)
    evidence_event_id: Optional[str] = None
    confirmation_event_id: Optional[str] = None


@dataclass
class RoutingDecision:
    """Decision made by the router."""
    signal_id: str
    route_key: str
    action: ActionType
    reason: str
    blocked: bool = False
    blocked_reason: Optional[str] = None
    cooldown_remaining_sec: Optional[int] = None


